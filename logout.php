<?php

require_once "config/functions.php";

/*
|--------------------------------------------------------------------------
| User Logout
|--------------------------------------------------------------------------
*/

$_SESSION = array();

/*
|--------------------------------------------------------------------------
| Destroy Session Cookie
|--------------------------------------------------------------------------
*/

if (ini_get("session.use_cookies")) {

    $params = session_get_cookie_params();

    setcookie(
        session_name(),
        "",
        time() - 42000,
        $params["path"],
        $params["domain"],
        $params["secure"],
        $params["httponly"]
    );
}

/*
|--------------------------------------------------------------------------
| Destroy Session
|--------------------------------------------------------------------------
*/

session_destroy();

/*
|--------------------------------------------------------------------------
| Redirect to Home
|--------------------------------------------------------------------------
*/

header("Location: index.php");
exit;

?>